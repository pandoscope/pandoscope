"""
Render the reconciler confs of meta for another org.

Format authority: the confs under ``scripts/`` in the meta repo
(``actions-credentials.conf`` documents the line grammar).
Settings, rulesets and collaborators reuse meta's own conf
and rewrite only what names the org.
Credentials are generated here,
because every value in meta's copy belongs to the pandoscope org.
Mirrored pair: a grammar change in meta's confs changes this module in the same arc.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

from pandoscope.org.plan import Repo

ORG_LINE = re.compile(r'^ORG="[^"]*"$', re.MULTILINE)
EXCEPT_ENTRY = re.compile(r'^(\s*"[^"|]+)\|except:[^"]*"', re.MULTILINE)


@dataclass(frozen=True)
class Credentials:
    """
    The org's Actions credential facts.

    ``app_slug`` is the release-bot GitHub App every workflow mints its token from.
    ``client_id`` is that app's client ID.
    ``board_url`` is the org project board, or None when the org has none yet.
    """

    app_slug: str
    client_id: str
    board_url: str | None


def retarget(conf: str, org: str) -> str:
    """
    Return ``conf`` with its ``ORG="..."`` line naming ``org``.

    Raises ValueError when ``conf`` has no ``ORG=`` line.
    """
    if not ORG_LINE.search(conf):
        msg = f"conf has no ORG= line to retarget to org={org!r}"
        raise ValueError(msg)
    return ORG_LINE.sub(f'ORG="{org}"', conf)


def retarget_excepts(conf: str, direct: list[str]) -> str:
    """
    Point every ``except:`` scope in ``conf`` at the ``direct`` repos.

    In meta every ``except:`` names the repos that take direct pushes,
    so the plan's direct-push repos replace it.
    With none, the entry widens to ``all``.
    """
    scope = f"except:{','.join(direct)}" if direct else "all"
    return EXCEPT_ENTRY.sub(rf'\1|{scope}"', conf)


def credentials_conf(org: str, plan: list[Repo], creds: Credentials) -> str:
    """
    Return an ``actions-credentials.conf`` for ``org``.

    BOT_MERGE_ENABLED is scoped ``only:`` the planned repos
    that do not take direct pushes.
    An ``except:`` scope computes its selection from the org's public repos,
    and an all-private org has none.
    Raises ValueError when the plan has no session-memory store.
    """
    names = [repo.name for repo in plan]
    if "session-memory" not in names:
        msg = f"plan for org={org!r} has no session-memory store: {names}"
        raise ValueError(msg)
    gated = ",".join(repo.name for repo in plan if not repo.direct_pushes)
    lines = [
        f"var|RELEASE_BOT_CLIENT_ID|all|{creds.client_id}",
        f"var|SESSION_MEMORY_REPO|all|{org}/session-memory",
        "var|LABELS_SYNC_ENABLED|all|true",
        f"var|BOT_MERGE_ENABLED|only:{gated}|true",
        "secret|RELEASE_BOT_PRIVATE_KEY|all|RELEASE_BOT_PRIVATE_KEY.pem",
        "secret|LABELS_TOKEN|all|LABELS_TOKEN",
        "secret|PUSH_BLOCKLIST|all|PUSH_BLOCKLIST",
    ]
    if creds.board_url:
        lines += [
            f"var|PROJECT_BOARD_URL|all|{creds.board_url}",
            "secret|PROJECT_BOARD_TOKEN|all|PROJECT_BOARD_TOKEN",
        ]
    body = "\n".join(f'    "{line}"' for line in lines)
    return (
        "# Generated by `pandoscope org init`; grammar authority:\n"
        "# meta's scripts/actions-credentials.conf.\n"
        "# shellcheck shell=bash\n\n"
        f'ORG="{org}"\n\n'
        f'MANAGED_APPS=(\n    "{creds.app_slug}"\n)\n\n'
        f"CREDENTIALS=(\n{body}\n)\n"
    )
